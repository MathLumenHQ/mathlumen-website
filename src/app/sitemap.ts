import type { MetadataRoute } from "next";
import { getArticles } from "@/lib/queries/articles";
import { getAllAuthors } from "@/lib/queries/authors";
import { getPowIssueHref, getPublishedPowIssues } from "@/lib/queries/pow";
import { SITE_URL, CATEGORIES } from "@/lib/constants";

export const revalidate = 86400;

/**
 * Generate a dynamic sitemap for search engine indexing.
 *
 * Rules:
 * - Every URL is absolute on SITE_URL (https://www.mathlumen.com).
 * - Only final, 200-status, indexable URLs are listed. Redirecting routes
 *   (e.g. /pow/latest) must never appear here.
 * - `lastModified` is set only where a real modification date exists; a
 *   fabricated "now" on every URL teaches Google to ignore the field.
 */
export default async function sitemap(): Promise<MetadataRoute.Sitemap> {
  const [articlesResult, authors, powIssues] = await Promise.all([
    getArticles({ limit: 1000 }),
    getAllAuthors(),
    getPublishedPowIssues({ limit: 1000 }),
  ]);

  const staticPages: MetadataRoute.Sitemap = [
    // Trailing slash matches the canonical emitted by createMetadata({ path: "/" }).
    { url: `${SITE_URL}/`, changeFrequency: "daily", priority: 1 },
    { url: `${SITE_URL}/articles`, changeFrequency: "daily", priority: 0.9 },
    { url: `${SITE_URL}/authors`, changeFrequency: "weekly", priority: 0.7 },
    { url: `${SITE_URL}/about`, changeFrequency: "monthly", priority: 0.5 },
    { url: `${SITE_URL}/newsletter`, changeFrequency: "monthly", priority: 0.5 },
    { url: `${SITE_URL}/archive`, changeFrequency: "daily", priority: 0.6 },
    { url: `${SITE_URL}/pow`, changeFrequency: "weekly", priority: 0.75 },
    // /pow/latest intentionally omitted: it redirects to the newest issue,
    // which is already listed below via getPowIssueHref().
    { url: `${SITE_URL}/pow/archive`, changeFrequency: "weekly", priority: 0.7 },
    { url: `${SITE_URL}/topics`, changeFrequency: "weekly", priority: 0.8 },
    { url: `${SITE_URL}/news`, changeFrequency: "daily", priority: 0.85 },
  ];

  const categoryPages: MetadataRoute.Sitemap = CATEGORIES.map((cat) => ({
    url: `${SITE_URL}/category/${cat.value}`,
    changeFrequency: "daily" as const,
    priority: 0.7,
  }));

  const articlePages: MetadataRoute.Sitemap = articlesResult.data.map((article) => ({
    url: `${SITE_URL}/articles/${article.slug}`,
    lastModified: article.updatedAt ? new Date(article.updatedAt) : undefined,
    changeFrequency: "weekly" as const,
    priority: 0.8,
  }));

  const authorPages: MetadataRoute.Sitemap = authors.map((author) => ({
    url: `${SITE_URL}/authors/${author.slug}`,
    changeFrequency: "monthly" as const,
    priority: 0.6,
  }));

  const powPages: MetadataRoute.Sitemap = powIssues.map((issue) => ({
    url: `${SITE_URL}${getPowIssueHref(issue.publicId)}`,
    lastModified: issue.updatedAt ? new Date(issue.updatedAt) : undefined,
    changeFrequency: "monthly" as const,
    priority: 0.7,
  }));

  // De-duplicate by URL in case a route is generated by more than one source.
  const seen = new Set<string>();
  return [
    ...staticPages,
    ...categoryPages,
    ...articlePages,
    ...authorPages,
    ...powPages,
  ].filter((entry) => {
    if (seen.has(entry.url)) return false;
    seen.add(entry.url);
    return true;
  });
}